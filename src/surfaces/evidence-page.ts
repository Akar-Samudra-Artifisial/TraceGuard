import type { EvidencePack } from '../core/trace';
import type { Hazard, Severity, TraceSnapshot } from '../core/types';

/** Context the page needs besides the pack itself. */
export interface EvidencePageContext {
  projectKey?: string;
  /** Site base URL such as https://acme.atlassian.net, used to link Jira keys. */
  siteUrl?: string;
  simulated: boolean;
  simulatedPullRequests: boolean;
}

type Colour = 'Grey' | 'Red' | 'Yellow' | 'Green' | 'Blue' | 'Purple';

const SEVERITY_COLOUR: Record<Severity, Colour> = { critical: 'Red', high: 'Yellow', medium: 'Blue', low: 'Grey' };
const RESULT_COLOUR = { passed: 'Green', failed: 'Red', 'not-run': 'Grey' } as const;

export function escapeXml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

const status = (title: string, colour: Colour) =>
  `<ac:structured-macro ac:name="status"><ac:parameter ac:name="colour">${colour}</ac:parameter>` +
  `<ac:parameter ac:name="title">${escapeXml(title)}</ac:parameter></ac:structured-macro>`;

const panel = (name: 'info' | 'note' | 'warning', body: string) =>
  `<ac:structured-macro ac:name="${name}"><ac:rich-text-body>${body}</ac:rich-text-body></ac:structured-macro>`;

const table = (head: string[], rows: string[][]) =>
  `<table><thead><tr>${head.map((h) => `<th>${escapeXml(h)}</th>`).join('')}</tr></thead><tbody>` +
  rows.map((r) => `<tr>${r.map((c) => `<td>${c || '—'}</td>`).join('')}</tr>`).join('') +
  '</tbody></table>';

/** "2026-11-01T10:32:05.123Z" → "2026-11-01 10:32 UTC". */
export function stamp(iso: string, seconds = false): string {
  return `${iso.slice(0, 10)} ${iso.slice(11, seconds ? 19 : 16)} UTC`;
}

export function evidencePageTitle(pack: EvidencePack, ctx: EvidencePageContext, seconds = false): string {
  const scope = ctx.projectKey && !ctx.simulated ? `${ctx.projectKey} ${pack.release}` : `release ${pack.release}`;
  return `TraceGuard evidence pack · ${scope} · ${stamp(pack.generatedAt, seconds)}`;
}

/**
 * Confluence storage-format body of the evidence pack: a frozen snapshot of coverage, open gaps
 * and the traceability matrix, with every Jira key linked when the site URL is known.
 */
export function renderEvidencePage(pack: EvidencePack, snapshot: TraceSnapshot, ctx: EvidencePageContext): string {
  const reqKey = new Map(snapshot.requirements.map((r) => [r.id, r.key]));
  const hazards = new Map<string, Hazard>(snapshot.hazards.map((h) => [h.id, h]));

  // Only keys of real Jira issues get links; pull request IDs such as PR-63 look alike but are not issues.
  const jiraKeys = new Set([
    ...snapshot.requirements.map((r) => r.key),
    ...snapshot.hazards.map((h) => h.key),
    ...snapshot.workItems.map((w) => w.key),
    ...snapshot.testCases.map((t) => t.key),
  ]);
  const issue = (key: string | undefined, label = key) => {
    if (!key || !label) return escapeXml(label ?? '');
    if (!ctx.siteUrl || ctx.simulated || !jiraKeys.has(key)) return escapeXml(label);
    return `<a href="${escapeXml(`${ctx.siteUrl}/browse/${key}`)}">${escapeXml(label)}</a>`;
  };
  const req = (id: string) => issue(reqKey.get(id), id);
  const list = (items: string[]) => items.join(', ');

  const { coverage } = pack;
  const source = ctx.simulated
    ? 'Built from the TraceGuard sample dataset, not from Jira issues.'
    : `Read live from Jira project ${ctx.projectKey ?? ''}.${ctx.simulatedPullRequests ? ' Pull requests are simulated history.' : ''}`;

  const intro =
    `<p>Traceability evidence for release <strong>${escapeXml(pack.release)}</strong>, generated by TraceGuard on ` +
    `<time datetime="${pack.generatedAt.slice(0, 10)}" /> at ${escapeXml(stamp(pack.generatedAt))}. ` +
    `This page is a snapshot: it does not change when Jira changes. Generate a new pack for current status.</p>`;

  const summary = table(
    ['Requirements', 'Fully traced', 'Coverage', 'Open gaps', 'Data source'],
    [[String(coverage.total), String(coverage.traced), `<strong>${coverage.percent}%</strong>`, String(pack.gaps.length), escapeXml(source)]],
  );

  const gaps = pack.gaps.length
    ? table(
        ['Severity', 'Gap', 'Requirement / artifact', 'Finding', 'Owner'],
        pack.gaps.map((g) => [
          status(g.severity, SEVERITY_COLOUR[g.severity]),
          escapeXml(g.code),
          g.requirementId ? req(g.requirementId) : issue(g.artifactKey),
          escapeXml(g.message),
          escapeXml(g.owner ?? ''),
        ]),
      )
    : `<p>${status('none', 'Green')} No open traceability gaps.</p>`;

  const matrix = table(
    ['Requirement', 'Title', 'Class', 'Hazards', 'Work items', 'Pull requests', 'Tests', 'Status'],
    pack.rows.map((r) => [
      req(r.requirementId),
      escapeXml(r.title),
      escapeXml(r.safetyClass),
      list(r.hazards.map((h) => issue(hazards.get(h)?.key, h))),
      list(r.workItems.map((k) => issue(k))),
      escapeXml(list(r.pullRequests)),
      list(r.tests.map((t) => `${issue(t.key)} ${status(t.result, RESULT_COLOUR[t.result])}`)),
      r.status === 'traced' ? status('traced', 'Green') : status('gap', 'Red'),
    ]),
  );

  const legend =
    '<p>G1 no work item · G2 no test · G3 failed test · G4 untraced safety-critical change · ' +
    'G5 verification older than the last code change · G6 requirement edited after approval.</p>';

  return [
    ctx.simulated ? panel('warning', `<p>${escapeXml(source)}</p>`) : '',
    intro,
    '<h2>Summary</h2>',
    summary,
    '<h2>Open gaps</h2>',
    gaps,
    legend,
    '<h2>Traceability matrix</h2>',
    matrix,
    panel(
      'note',
      '<p>TraceGuard reports traceability status only. It does not certify compliance with IEC 62304, ISO 14971 or any other standard.</p>',
    ),
  ].join('');
}
